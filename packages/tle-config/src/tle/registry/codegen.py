def target_path(root: Path | None = None) -> Path:
    return (root or repo_root()) / "packages" / "tle-engine" / "src" / "tle" / "params" / "_generated.py"


def write(root: Path | None = None) -> Path:
    root = root or repo_root()
    path = target_path(root)
    path.write_text(generate(load_registry(root)))
    return path


def is_current(root: Path | None = None) -> bool:
    root = root or repo_root()
    path = target_path(root)
    return path.exists() and path.read_text() == generate(load_registry(root))
